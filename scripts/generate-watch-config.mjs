import { readFile, rename, writeFile } from 'node:fs/promises'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const DEFAULT_OUTPUT = resolve(ROOT, 'watch/app-side/api-config.js')
const LOCAL_ENV = resolve(ROOT, 'watch/.env.local')
const DEFAULT_ORIGIN = 'http://127.0.0.1:8080'

function parseLocalOrigin(text) {
  for (const rawLine of text.split(/\r?\n/)) {
    const line = rawLine.trim()
    if (!line || line.startsWith('#')) continue
    const separator = line.indexOf('=')
    if (separator < 1) continue
    const key = line.slice(0, separator).trim()
    if (key !== 'JARVIS_WATCH_API_ORIGIN') continue
    return line.slice(separator + 1).trim().replace(/^(['"])(.*)\1$/, '$2')
  }
  return ''
}

async function configuredOrigin({ ignoreLocalOverride = false } = {}) {
  if (process.env.JARVIS_WATCH_API_ORIGIN?.trim()) {
    return { value: process.env.JARVIS_WATCH_API_ORIGIN.trim(), source: 'environment' }
  }
  if (!ignoreLocalOverride) {
    try {
      const localValue = parseLocalOrigin(await readFile(LOCAL_ENV, 'utf8'))
      if (localValue) return { value: localValue, source: 'local-override' }
    } catch (error) {
      if (error.code !== 'ENOENT') throw error
    }
  }
  return { value: DEFAULT_ORIGIN, source: 'safe-default' }
}

function validateOrigin(value) {
  const parsed = new URL(value)
  if (!['http:', 'https:'].includes(parsed.protocol)) {
    throw new Error('JARVIS_WATCH_API_ORIGIN must use HTTP or HTTPS')
  }
  if (parsed.username || parsed.password || parsed.pathname !== '/' || parsed.search || parsed.hash) {
    throw new Error('JARVIS_WATCH_API_ORIGIN must be an origin without credentials, path, query, or fragment')
  }
  return parsed.origin
}

function outputPath(argv) {
  const index = argv.indexOf('--output')
  if (index === -1) return DEFAULT_OUTPUT
  if (!argv[index + 1]) throw new Error('--output requires a path')
  return resolve(argv[index + 1])
}

async function main() {
  const argv = process.argv.slice(2)
  const configured = await configuredOrigin({
    ignoreLocalOverride: argv.includes('--ignore-local-override'),
  })
  const origin = validateOrigin(configured.value)
  const output = outputPath(argv)
  const temporary = `${output}.tmp-${process.pid}`
  const content = [
    '// Generated by scripts/generate-watch-config.mjs; do not commit.',
    `export const API_ORIGIN = ${JSON.stringify(origin)}`,
    "export const API_BASE = `${API_ORIGIN}/api/v1`",
    '',
  ].join('\n')
  await writeFile(temporary, content, { mode: 0o600 })
  await rename(temporary, output)
  process.stdout.write(`watch_api_config=generated source=${configured.source}\n`)
}

main().catch((error) => {
  process.stderr.write(`watch_api_config=failed reason=${error.message}\n`)
  process.exitCode = 1
})
